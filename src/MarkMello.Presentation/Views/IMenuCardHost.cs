using Avalonia;

namespace MarkMello.Presentation.Views;

/// <summary>
/// Окно, которое показывает меню карточками внутри себя (ADR-0009 Rule 4): меню сайдбара
/// и список «ещё N» у вкладок. Вид знает, от чего раскрывается меню, — от кнопки или от
/// точки клика, — а окно держит слой карточек, считает позицию и следит за фокусом.
/// </summary>
internal interface IMenuCardHost
{
    /// <summary>
    /// Запомнить, от чего раскрывается следующее меню: <paramref name="anchor"/> — рамка
    /// кнопки или точка клика в координатах <paramref name="source"/>. Карточка встаёт
    /// под якорем, выровненная по его левому краю, а список «ещё N» — по правому.
    /// </summary>
    void AnchorMenuCard(Visual source, Rect anchor);

    /// <summary>
    /// Раскрыть следующее меню под кнопкой <paramref name="trigger"/>. Окно берёт её рамку
    /// заново при каждой расстановке: кнопка может сдвинуться или сменить ширину, пока
    /// меню открыто, — «ещё 10» становится «ещё 9», — и карточка идёт за ней.
    /// </summary>
    void AnchorMenuCard(Visual trigger);

    /// <summary>Перевести фокус в открытую карточку — для меню, вызванного с клавиатуры.</summary>
    void FocusMenuCard();
}
